#!/usr/bin/env bash
# ==============================================================================
# Студия СЛАУ и Дифференциальных Уравнений — Автоматический запуск (Linux / macOS)
# ==============================================================================
set -e
cd "$(dirname "$0")"

echo "=============================================================================="
echo "🚀 Инициализация Студии СЛАУ и Дифференциальных Уравнений"
echo "=============================================================================="

# 1. Проверка .env
if [ ! -f .env ]; then
  if [ -f .env.example ]; then
    cp .env.example .env
  else
    echo "GEMINI_API_KEY=" > .env
  fi
  echo "[+] Файл .env создан."
fi

# 2. Автоматическая синхронизация всех npm зависимостей
echo "[*] Проверка и синхронизация всех библиотек (npm install)..."
npm install

# 3. Сборка проекта
echo "[*] Сборка проекта (npm run build)..."
NODE_ENV=production npm run build

# 4. Запуск сервера
echo "=============================================================================="
echo "✨ Студия готова к работе!"
echo "🌐 Адрес: http://localhost:3000"
echo "=============================================================================="
npm start
